export type TranslationKey = keyof typeof translations;

export function translate(locale: Locale, key: string): string {
  if (locale === "en") return key;
  const curated = translations[key as TranslationKey]?.[locale];
  const normalizedEnum = translations[key.toUpperCase().replaceAll(" ", "_") as TranslationKey]?.[locale];
  const generated = generatedTranslations[key]?.[locale];
  return curated ?? normalizedEnum ?? generated ?? key;
}

export function formatLocalizedDate(locale: Locale, value: Date | string | number, options?: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(`${locale}-IN`, options).format(new Date(value));
}

export function formatLocalizedNumber(locale: Locale, value: number, options?: Intl.NumberFormatOptions) {
  return new Intl.NumberFormat(`${locale}-IN`, options).format(value);
}
